def run_reference_search(
    algorithm,
    start,
    goal,
    cost="distance_km",
    heuristic_fn=None,
):
    root = Node(state=start)
    is_depth_first = algorithm == "DFS"
    is_breadth_first = algorithm == "BFS"
    uses_costs = not (is_depth_first or is_breadth_first)
    tie_breaker = itertools.count()

    if is_breadth_first:
        frontier = deque([root])
    elif is_depth_first:
        frontier = [root]
    else:
        root_h = heuristic_fn(start) if heuristic_fn else 0.0
        frontier = [(root.path_cost + root_h, next(tie_breaker), root)]

    reached = {start: 0.0} if uses_costs else {start}
    expanded_nodes = 0
    generated_nodes = 0
    max_frontier_size = 1
    expanded_order = []

    while frontier:
        if is_breadth_first:
            node = frontier.popleft()
        elif is_depth_first:
            node = frontier.pop()
        else:
            priority, _, node = heapq.heappop(frontier)
            if node.path_cost != reached.get(node.state):
                continue

        if node.state == goal:
            return build_result(
                algorithm,
                node,
                expanded_nodes,
                generated_nodes,
                max_frontier_size,
                expanded_order,
            )

        expanded_nodes += 1
        expanded_order.append(node.state)
        neighbours = successors(node.state)
        if is_depth_first:
            neighbours = list(reversed(neighbours))

        for neighbour in neighbours:
            step_cost = graph[node.state][neighbour][cost]
            child_cost = node.path_cost + step_cost

            if uses_costs:
                if child_cost >= reached.get(neighbour, math.inf):
                    continue
                reached[neighbour] = child_cost
            else:
                if neighbour in reached:
                    continue
                reached.add(neighbour)

            child = Node(
                state=neighbour,
                parent=node,
                path_cost=child_cost,
                depth=node.depth + 1,
            )

            if is_breadth_first:
                frontier.append(child)
            elif is_depth_first:
                frontier.append(child)
            else:
                h_value = heuristic_fn(neighbour) if heuristic_fn else 0.0
                heapq.heappush(
                    frontier,
                    (
                        child_cost + h_value,
                        next(tie_breaker),
                        child,
                    ),
                )
            generated_nodes += 1

        max_frontier_size = max(max_frontier_size, len(frontier))

    return build_result(
        algorithm,
        None,
        expanded_nodes,
        generated_nodes,
        max_frontier_size,
        expanded_order,
    )


