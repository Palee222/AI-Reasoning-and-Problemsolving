def astar(problem, heuristic, cost="distance_km", trace=False):

    root = Node(state=problem.initial_state, path_cost=0)

    tie_breaker = count()

    frontier = []

    root_h = heuristic(root.state)

    heapq.heappush(frontier,(root.path_cost + root_h, next(tie_breaker), root))

    # reached[state] = cheapest g(n) discovered so far
    reached = {root.state: 0}

    expanded_nodes = 0
    max_frontier = 1
    step = 0

    while frontier:
        f_value, _, node = heapq.heappop(frontier)

        # Ignore obsolete, more expensive paths.
        if (node.path_cost!=reached.get(node.state)):
            continue

        step += 1

        h_value = heuristic(node.state)

        if trace:
            print(f"\nSTEP {step}")

            print(
                f"POP: {pretty_name(node.state)} "
                f"g={node.path_cost:.2f} "
                f"h={h_value:.2f} "
                f"f={f_value:.2f}"
            )

        if problem.is_goal(node.state):

            return make_result(
                problem,
                node,
                expanded_nodes,
                max_frontier
            )

        expanded_nodes += 1

        for child in expand(
            problem,
            node,
            cost=cost
        ):

            child_g = (
                child.path_cost
            )

            if (
                child.state not in reached
                or
                child_g
                <
                reached[child.state]
            ):

                reached[
                    child.state
                ] = child_g

                child_h = heuristic(
                    child.state
                )

                child_f = (
                    child_g
                    +
                    child_h
                )

                heapq.heappush(
                    frontier,
                    (
                        child_f,
                        next(tie_breaker),
                        child
                    )
                )

        max_frontier = max(
            max_frontier,
            len(frontier)
        )

        if trace:

            active_frontier = []

            for f, _, n in frontier:

                if (
                    reached.get(n.state)
                    ==
                    n.path_cost
                ):

                    active_frontier.append(
                        (
                            round(f, 2),
                            pretty_name(n.state)
                        )
                    )

            active_frontier.sort()

            print(
                "Frontier:",
                active_frontier
            )

    return None


