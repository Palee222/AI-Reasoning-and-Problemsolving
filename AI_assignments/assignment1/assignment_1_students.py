def validate_path(
    path,
    start,
    goal,
):

    if not path:
        return False

    start = normalize_city(
        start
    )

    goal = normalize_city(
        goal
    )

    # Require canonical city identifiers.
    if path[0] != start:
        return False

    if path[-1] != goal:
        return False

    for city in path:

        if city not in graph:
            return False

    for city_a, city_b in zip(
        path[:-1],
        path[1:],
    ):

        if city_b not in graph[city_a]:
            return False

    return True

