def expand(problem, node, cost="distance_km"):
    children = []

    for action in sorted(problem.actions(node.state)):

        next_state = problem.result(
            node.state,
            action
        )

        step_cost = problem.graph[
            node.state
        ][next_state][cost]

        child = Node(
            state=next_state,
            parent=node,
            action=action,
            path_cost=node.path_cost + step_cost,
            depth=node.depth + 1
        )

        children.append(child)

    return children
