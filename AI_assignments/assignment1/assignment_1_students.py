def path_metrics(path):

    if path is None:
        return {
            "path_length": None,
            "distance_km": None,
            "time_min": None,
        }

    distance = 0.0
    time = 0.0

    for city_a, city_b in zip(
        path[:-1],
        path[1:],
    ):

        distance += (
            graph[city_a]
            [city_b]
            ["distance_km"]
        )

        time += (
            graph[city_a]
            [city_b]
            ["time_min"]
        )

    return {
        "path_length":
            len(path) - 1,

        "distance_km":
            float(distance),

        "time_min":
            float(time),
    }

