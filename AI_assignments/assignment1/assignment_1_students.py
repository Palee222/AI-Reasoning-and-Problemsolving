def build_result(
    algorithm,
    node,
    expanded_nodes,
    generated_nodes,
    max_frontier_size,
    expanded_order,
):

    # --------------------------------------------------------
    # Failure
    # --------------------------------------------------------

    if node is None:

        return {

            "algorithm":
                algorithm,

            "solution": {

                "found":
                    False,

                "path":
                    None,

                "path_length":
                    None,

                "distance_km":
                    None,

                "time_min":
                    None,
            },

            "diagnostics": {

                "expanded_nodes":
                    int(expanded_nodes),

                "generated_nodes":
                    int(generated_nodes),

                "max_frontier_size":
                    int(max_frontier_size),

                "expanded_order":
                    list(expanded_order),
            },
        }

    # --------------------------------------------------------
    # Success
    # --------------------------------------------------------

    path = reconstruct_path(
        node
    )

    metrics = path_metrics(
        path
    )

    return {

        "algorithm":
            algorithm,

        "solution": {

            "found":
                True,

            "path":
                path,

            **metrics,
        },

        "diagnostics": {

            "expanded_nodes":
                int(expanded_nodes),

            "generated_nodes":
                int(generated_nodes),

            "max_frontier_size":
                int(max_frontier_size),

            "expanded_order":
                list(expanded_order),
        },
    }

