def bfs(problem, trace=False):
    """
    Selection rule: shallowest node first
    Frontier: FIFO queue
    Repeated states: ignored once reached
    Goal test: when a child is generated
    """

    root = Node(
        state=problem.initial_state
    )

    if problem.is_goal(root.state):
        return build_result(
            problem,
            root,
            expanded_nodes=0,
            max_frontier=1
        )

    frontier = deque([root])

    reached = {
        root.state
    }

    expanded_nodes = 0
    max_frontier = 1
    step = 0

    while frontier:

        node = frontier.popleft()

        expanded_nodes += 1
        step += 1

        if trace:

            print(
                f"\nSTEP {step}"
            )

            print(
                "POP:",
                pretty_name(node.state)
            )

        for child in expand(
            problem,
            node,
            cost="distance_km"
        ):

            if child.state in reached:
                continue

            reached.add(child.state)

            # BFS can use an early goal test.
            if problem.is_goal(child.state):

                if trace:
                    print(
                        "GOAL GENERATED:",
                        pretty_name(child.state)
                    )

                max_frontier = max(
                    max_frontier,
                    len(frontier) + 1
                )

                return build_result(
                    problem,
                    child,
                    expanded_nodes,
                    max_frontier
                )

            frontier.append(child)

        max_frontier = max(
            max_frontier,
            len(frontier)
        )

        if trace:

            print(
                "Frontier:",
                [
                    pretty_name(n.state)
                    for n in frontier
                ]
            )

            print(
                "Reached:",
                [
                    pretty_name(s)
                    for s in sorted(reached)
                ]
            )

    return None

