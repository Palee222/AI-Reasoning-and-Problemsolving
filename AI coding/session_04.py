class RouteProblem:

    def __init__(
        self,
        graph,
        initial_state="bucharest",
        goal_state="rome"
    ):
        self.graph = graph
        self.initial_state = normalize_city(initial_state)
        self.goal_state = normalize_city(goal_state)

    def actions(self, state):
        """
        Return the cities directly reachable from state.
        """
        return list(self.graph[state].keys())

    def result(self, state, action):
        """
        In this route problem, the action itself tells us
        the destination city.
        """
        return action

    def is_goal(self, state):
        return state == self.goal_state

    def action_cost(self, state, action, next_state):
        """
        Default action cost used in previous examples:
        distance in kilometres.
        """
        return self.graph[state][next_state]["distance_km"]


