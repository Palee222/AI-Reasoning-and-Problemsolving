@dataclass
class Node:

    state: str
    parent: object = None
    action: object = None
    path_cost: float = 0
    depth: int = 0


# A search node represents one particular way
# of reaching a state.
#
# STATE     -> where we are
# PARENT    -> the search node we came from
# ACTION    -> the action used to get here
# PATH-COST -> accumulated cost g(n)
# DEPTH     -> number of actions from the root


# ============================================================
# 9. EXPAND
# ============================================================

def expand(problem, node, cost="distance_km"):
    """
    Generate the children of a search node.

    Successors are considered alphabetically so that
    all runs are deterministic.

    Child path cost:

        child.PATH-COST
        =
        parent.PATH-COST
        +
        ACTION-COST(s, action, s')
    """

    children = []

    for action in sorted(problem.actions(node.state)):

        next_state = problem.result(
            node.state,
            action
        )

        step_cost = problem.graph[
            node.state
        ][next_state][cost]

        child = Node(
            state=next_state,
            parent=node,
            action=action,
            path_cost=node.path_cost + step_cost,
            depth=node.depth + 1
        )

        children.append(child)

    return children


