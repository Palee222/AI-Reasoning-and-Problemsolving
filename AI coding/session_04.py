def solution_path(node):
    """
    Reconstruct the path from the initial state
    to the current node.
    """

    path = []

    while node is not None:
        path.append(node.state)
        node = node.parent

    return list(reversed(path))


def solution_actions(node):
    """
    Reconstruct the sequence of actions.
    """

    actions = []

    while node is not None and node.parent is not None:
        actions.append(node.action)
        node = node.parent

    return list(reversed(actions))


def path_cost(problem, path, metric):
    """
    Compute a path's total distance or total time
    directly from the graph.
    """

    total = 0

    for city_a, city_b in zip(
        path[:-1],
        path[1:]
    ):
        total += problem.graph[
            city_a
        ][city_b][metric]

    return total


def make_result(
    problem,
    node,
    expanded_nodes,
    max_frontier
):
    """
    Create the same output structure for every algorithm.
    """

    path = solution_path(node)

    return {
        "path": path,
        "actions": len(path) - 1,
        "distance_km": path_cost(
            problem,
            path,
            "distance_km"
        ),
        "time_min": path_cost(
            problem,
            path,
            "time_min"
        ),
        "expanded_nodes": expanded_nodes,
        "max_frontier": max_frontier
    }

