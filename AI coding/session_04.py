# ============================================================

# Q1.
# Why can BFS return a route with fewer actions
# but a higher total distance?
#
# BFS orders search nodes by depth.
#
# It minimises the number of actions, not the accumulated
# distance.
#
# When action costs differ:
#
#     fewer actions != lower cost


# ------------------------------------------------------------

# Q2.
# Why does DFS depend on successor ordering?
#
# DFS commits to one branch and explores it deeply
# before returning to the alternatives.
#
# Therefore, changing which successor is considered
# first can completely change:
#
#     - the exploration order
#     - the first solution found
#     - the number of nodes expanded


# ------------------------------------------------------------

# Q3.
# Why does UCS use a priority queue?
#
# UCS must always select the frontier node with
# minimum accumulated path cost:
#
#     g(n)
#
# A priority queue maintains exactly this ordering.


# ------------------------------------------------------------

# Q4.
# Why can UCS replace a previously reached route?
#
# Reaching a state does not prove that we have reached
# it through the cheapest possible path.
#
# Example:
#
#     first route to X:
#         g(X) = 900
#
#     later route to X:
#         g(X) = 700
#
# UCS keeps:
#
#     reached[X] = 700


# ------------------------------------------------------------

# Q5.
# Why does UCS test the goal when it is popped,
# rather than when it is generated?
#
# Generating a goal only proves that a solution exists.
#
# There may still be a cheaper partial path in the frontier
# that later reaches the goal with a lower total cost.
#
# UCS therefore stops only when the goal itself is the
# lowest-cost node in the frontier.
#
#     goal generated
#         !=
#     optimality guaranteed
#
#     goal popped with minimum g(n)
#         =
#     optimal solution


# ------------------------------------------------------------

# Q6.
# Which strategy uses the most memory?
#
# For THIS concrete run, inspect:
#
#     comparison.loc["Max frontier"]
#
# The answer should be based on the observed run.
#
# In general:
#
# BFS can consume substantial memory because it keeps
# many nodes from the same depth.
#
# DFS usually keeps much less frontier information.
#
# UCS can also consume substantial memory because many
# alternative low-cost paths may remain in the frontier.


# ------------------------------------------------------------

# Q7.
# What happens if every connection has cost 1?
#
# Then:
#
#     g(n) = depth(n)
#
# Therefore:
#
#     lowest g(n)
#
# and:
#
#     shallowest depth
#
# describe the same ordering criterion.
#
# UCS and BFS therefore become equivalent with respect
# to solution cost/depth, apart from possible tie-breaking.


# ------------------------------------------------------------

# Q8.
# What information are BFS, DFS and UCS still missing?
#
# None of them estimates how far a state is from Rome.
#
# BFS:
#     knows depth
#
# DFS:
#     follows depth-first exploration
#
# UCS:
#     knows cost already spent, g(n)
#
# None of them knows:
#
#     estimated cost remaining to the goal
#
# In the next session we introduce:
#
#     h(n)
#
# the heuristic estimate of the remaining cost.
#
# This leads to informed search and A*.

