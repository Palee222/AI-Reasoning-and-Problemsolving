#     ]
#
# At this exact moment, the frontier contains exactly
# the newly generated search nodes.
#
# 3. States reached so far:
#
#     Reached = {
#         Bucharest,
#         Belgrade,
#         Budapest,
#         Sofia
#     }
#
# Key distinction:
#
# Generated now:
#     Belgrade-node, Budapest-node, Sofia-node
#
# Frontier:
#     search nodes waiting to be explored
#
# Reached:
#     states discovered at any point so far
#
# Important:
#     Frontier contains SEARCH NODES.
#     Reached contains STATES.



# ============================================================
# EXERCISE — WHICH NODE IS EXPANDED NEXT?
# ============================================================
# What determines which node is expanded next?
#
# BFS:
#     Expands the SHALLOWEST node in the frontier.
#     It uses a FIFO queue.
#
# DFS:
#     Expands the DEEPEST node in the frontier.
#     It uses a LIFO stack.
#
# UCS:
#     Expands the node with the LOWEST accumulated
#     path cost g(n).
#     It uses a priority queue.
#
#
# In short:
#
#     BFS -> minimum depth
#     DFS -> maximum depth
#     UCS -> minimum g(n)
#
#
# IMPORTANT:
# None of these algorithms estimates which node is
# geographically closer to Rome.
# That would require heuristic information.
# ============================================================
# AFTER THE FIRST EXPANSION
# ============================================================
# After expanding Bucharest:
#
# Generated:
#     Belgrade-node
#     Budapest-node
#     Sofia-node
#
# Frontier:
#     [Belgrade-node, Budapest-node, Sofia-node]
#
# Reached:
#     {Bucharest, Belgrade, Budapest, Sofia}
# ============================================================
# EXPAND THE NEXT NODE — BFS / DFS EXAMPLE
# ============================================================
# With our alphabetical successor convention, both BFS
# and DFS select Belgrade next at this point.
#
# We now remove Belgrade-node from the frontier
# and expand it.
#
# After repeated-state checking, the new useful search
# node generated from Belgrade is:
#
#     Zagreb-node
#
#
# Therefore:
# ------------------------------------------------------------
# GENERATED NODES
# ------------------------------------------------------------
# Generated nodes are ONLY the new search nodes created
# during THIS expansion.
#
# Generated now:
#
#     Zagreb-node
# ------------------------------------------------------------
# FRONTIER
# ------------------------------------------------------------
# The frontier contains search nodes that have been
# generated but have NOT yet been expanded.
#
# Belgrade is no longer in the frontier because
# we have just expanded it.
#
# The frontier now contains:
#
#     Budapest-node
#     Sofia-node
#     Zagreb-node
#
# The exact order in which these nodes will be selected
# depends on the search strategy.
# ------------------------------------------------------------
# REACHED
# ------------------------------------------------------------
# Reached contains every STATE discovered so far.
#
# Reached:
#
#     {
#         Bucharest,
#         Belgrade,
#         Budapest,
#         Sofia,
#         Zagreb
#     }
#
# Notice that Belgrade is STILL in reached even though
# it is no longer in the frontier.
# ============================================================
# KEY DISTINCTION
# ============================================================
# Generated:
#     What did this expansion create?
#
# Frontier:
#     What search nodes are still waiting to be explored?
#
# Reached:
#     What states have been discovered at any point so far?
#
#
# After expanding Belgrade:
#
#     Generated = {Zagreb-node}
#
#     Frontier  = {
#         Budapest-node,
#         Sofia-node,
#         Zagreb-node
#     }
#
#     Reached   = {
#         Bucharest,
#         Belgrade,
#         Budapest,
#         Sofia,
#         Zagreb
#     }
#
#
# This makes the difference clearer:
#
#     Belgrade is REACHED,
#     but it is no longer in the FRONTIER.
#
#     Zagreb has just been GENERATED,
#     so it is both in the FRONTIER
#     and represented in REACHED.

# ============================================================
# 13. BREADTH-FIRST SEARCH — BFS
# ============================================================

def bfs(problem, trace=False):
    """
    Breadth-First Search.

    Selection rule:
        shallowest node first

    Frontier:
        FIFO queue

    Repeated states:
        ignored once reached

    Goal test:
        when a child is generated
    """

    root = Node(
        state=problem.initial_state
    )

    if problem.is_goal(root.state):
        return make_result(
            problem,
            root,
            expanded_nodes=0,
            max_frontier=1
        )

    frontier = deque([root])

    reached = {
        root.state
    }

    expanded_nodes = 0
    max_frontier = 1
    step = 0

    while frontier:

        node = frontier.popleft()

        expanded_nodes += 1
        step += 1

        if trace:

            print(
                f"\nSTEP {step}"
            )

            print(
                "POP:",
                pretty_name(node.state)
            )

        for child in expand(
            problem,
            node,
            cost="distance_km"
        ):

            if child.state in reached:
                continue

            reached.add(child.state)

            # BFS can use an early goal test.
            if problem.is_goal(child.state):

                if trace:
                    print(
                        "GOAL GENERATED:",
                        pretty_name(child.state)
                    )

                max_frontier = max(
                    max_frontier,
                    len(frontier) + 1
                )

                return make_result(
                    problem,
                    child,
                    expanded_nodes,
                    max_frontier
                )

            frontier.append(child)

        max_frontier = max(
            max_frontier,
            len(frontier)
        )

        if trace:

            print(
                "Frontier:",
                [
                    pretty_name(n.state)
                    for n in frontier
                ]
            )

            print(
                "Reached:",
                [
                    pretty_name(s)
                    for s in sorted(reached)
                ]
            )

    return None


# ============================================================
# 14. DEPTH-FIRST SEARCH — DFS
# ============================================================

def dfs(problem, trace=False):
    """
    Depth-First Search.

    Selection rule:
        deepest node first

    Frontier:
        LIFO stack

    We use repeated-state checking so that the algorithm
    does not repeatedly explore the same city.

    Successors are VISITED alphabetically.

    Because the stack is LIFO, children must be pushed
    in reverse alphabetical order.
    """

    root = Node(
        state=problem.initial_state
    )

    frontier = [root]

    reached = {
        root.state
    }

    expanded_nodes = 0
    max_frontier = 1
    step = 0

    while frontier:

        node = frontier.pop()

        step += 1

        if trace:

            print(
                f"\nSTEP {step}"
            )

            print(
                "POP:",
                pretty_name(node.state)
            )

        if problem.is_goal(node.state):

            return make_result(
                problem,
                node,
                expanded_nodes,
                max_frontier
            )

        expanded_nodes += 1

        children = []

        for child in expand(
            problem,
            node,
            cost="distance_km"
        ):

            if child.state not in reached:

                reached.add(child.state)

                children.append(child)

        # expand() returns alphabetical order.
        #
        # Example:
        #
        # [Belgrade, Budapest, Sofia]
        #
        # To visit Belgrade first with a LIFO stack,
        # push:
        #
        # Sofia, Budapest, Belgrade

        for child in reversed(children):
            frontier.append(child)

        max_frontier = max(
            max_frontier,
            len(frontier)
        )

        if trace:

            print(
                "Frontier:",
                [
                    pretty_name(n.state)
                    for n in reversed(frontier)
                ]
            )

            print(
                "Reached:",
                [
                    pretty_name(s)
                    for s in sorted(reached)
                ]
            )

    return None


# ============================================================
# 15. UNIFORM-COST SEARCH — UCS
# ============================================================

def ucs(
    problem,
    cost="distance_km",
    trace=False
):
    """
    Uniform-Cost Search.

    Selection rule:
        lowest accumulated path cost g(n)

    Frontier:
        priority queue

    A state can be reached again if the new route
    is cheaper.

    Goal test:
        when the node is popped from the frontier
    """

    if cost not in {
        "distance_km",
        "time_min"
    }:
        raise ValueError(
            "cost must be 'distance_km' or 'time_min'"
        )

    root = Node(
        state=problem.initial_state,
        path_cost=0
    )

    tie_breaker = count()

    frontier = []

    heapq.heappush(
        frontier,
        (
            0,
            next(tie_breaker),
            root
        )
    )

    # reached[state] contains the cheapest
    # path cost discovered so far.
    reached = {
        root.state: 0
    }

    expanded_nodes = 0
    max_frontier = 1
    step = 0

    while frontier:

        current_cost, _, node = heapq.heappop(
            frontier
        )

        # There may be an older, more expensive entry
        # for the same state still inside the heap.
        #
        # If so, ignore it.
        if current_cost != reached.get(node.state):
            continue

        step += 1

        if trace:

            print(
                f"\nSTEP {step}"
            )

            print(
                f"POP: {pretty_name(node.state)} "
                f"g={current_cost}"
            )

        # UCS uses a late goal test.
        #
        # A generated goal is not necessarily optimal.
        # A goal popped with minimum g(n) is optimal.
        if problem.is_goal(node.state):

            return make_result(
                problem,
                node,
                expanded_nodes,
                max_frontier
            )

        expanded_nodes += 1

        for child in expand(
            problem,
            node,
            cost=cost
        ):

            child_cost = child.path_cost

            # Keep the child if:
            #
            # 1. we have never reached this state, or
            # 2. this is a cheaper path to the state.

            if (
                child.state not in reached
                or
                child_cost < reached[child.state]
            ):

                reached[child.state] = child_cost

                heapq.heappush(
                    frontier,
                    (
                        child_cost,
                        next(tie_breaker),
                        child
                    )
                )

        max_frontier = max(
            max_frontier,
            len(frontier)
        )

        if trace:

            active_frontier = []

            for g, _, n in frontier:

                if reached.get(n.state) == g:

                    active_frontier.append(
                        (
                            g,
                            pretty_name(n.state)
                        )
                    )

            active_frontier.sort()

            print(
                "Frontier:",
                active_frontier
            )

            print(
                "Reached:",
                {
                    pretty_name(s): g
                    for s, g
                    in sorted(reached.items())
                }
            )

    return None


